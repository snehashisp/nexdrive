#!/usr/bin/env node
/**
 * Post-build step for NexDrive (runs after `vite build`, see package.json).
 *
 * Generates the service worker's full precache list: scan dist/ for cacheable
 * assets and write dist/sw-precache.js. sw.js imports it, so every shipped
 * asset is cached for offline use on install — not only the hand-listed CORE shell.
 *
 * It also writes a version stamp (a hash of every file's contents). sw.js uses it
 * in its cache name, so each deploy that changes any file replaces the old offline
 * copy on users' phones automatically.
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = __dirname;
const DIST = path.join(ROOT, 'dist');

// Extensions worth precaching for offline. (Skip source maps and the SW files.)
const CACHE_EXT = new Set([
  '.html', '.js', '.css', '.json', '.webmanifest',
  '.svg', '.png', '.jpg', '.jpeg', '.webp', '.ico', '.woff2', '.woff',
]);
const SKIP_FILES = new Set(['sw.js', 'sw-precache.js']);

function* walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else yield full;
  }
}

function main() {
  if (!fs.existsSync(path.join(DIST, 'index.html'))) {
    console.error('build: dist/index.html missing — run `vite build` first (npm run build does both)');
    process.exit(1);
  }

  const urls = [];
  const hash = crypto.createHash('sha256');
  let bytes = 0;
  for (const file of walk(DIST)) {
    const base = path.basename(file);
    if (SKIP_FILES.has(base)) continue;
    if (!CACHE_EXT.has(path.extname(file).toLowerCase())) continue;
    const rel = '/' + path.relative(DIST, file).split(path.sep).join('/');
    urls.push(rel);
    bytes += fs.statSync(file).size;
  }
  urls.sort();
  for (const rel of urls) hash.update(rel).update(fs.readFileSync(path.join(DIST, rel)));
  const version = hash.digest('hex').slice(0, 12);

  const banner = '/* AUTO-GENERATED by build.js — do not edit. */\n';
  const body =
    'self.__PRECACHE_VERSION = ' + JSON.stringify(version) + ';\n' +
    'self.__PRECACHE_URLS = ' + JSON.stringify(urls, null, 2) + ';\n';
  fs.writeFileSync(path.join(DIST, 'sw-precache.js'), banner + body);

  const mb = (bytes / (1 << 20)).toFixed(1);
  console.log(`build: precache manifest written — ${urls.length} assets (${mb} MB), version ${version} -> dist/sw-precache.js`);
}

main();
